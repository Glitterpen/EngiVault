-- Version only future PDF outputs. No historical row, stored PDF/ZIP, figure,
-- revision, workflow or audit record is rewritten by this migration.
-- Activation order: release both version-aware web and processor code first,
-- drain old processor workers, then apply this migration. Old unmarked queued
-- packages intentionally retain the legacy renderer, even after activation.
begin;
set local lock_timeout = '5s';

alter table public.work_package_items
  add column if not exists document_title text;

create or replace function public.stamp_project_report_pdf_layout()
returns trigger language plpgsql security invoker set search_path='' as $$
begin
  if tg_op='INSERT' then
    new.snapshot:=new.snapshot||jsonb_build_object('pdf_layout_version',2);
  else
    -- An existing report may be explicitly regenerated by the current workflow.
    -- INSERT ... ON CONFLICT also runs this branch: keep its original format,
    -- rather than adopting the marker from the excluded INSERT snapshot.
    new.snapshot:=new.snapshot-'pdf_layout_version';
    if old.snapshot ? 'pdf_layout_version' then
      new.snapshot:=new.snapshot||jsonb_build_object(
        'pdf_layout_version',old.snapshot->'pdf_layout_version');
    end if;
  end if;
  return new;
end $$;

create or replace function public.stamp_transmittal_pdf_layout()
returns trigger language plpgsql security invoker set search_path='' as $$
begin
  if tg_op='INSERT' then
    if new.manifest->>'kind'='document_transmittal' then
      new.manifest:=new.manifest||jsonb_build_object('pdf_layout_version',2);
    else
      new.manifest:=new.manifest-'pdf_layout_version';
    end if;
  else
    new.manifest:=new.manifest-'pdf_layout_version';
    if old.manifest ? 'pdf_layout_version' then
      new.manifest:=new.manifest||jsonb_build_object(
        'pdf_layout_version',old.manifest->'pdf_layout_version');
    end if;
  end if;
  return new;
end $$;

create or replace function public.freeze_transmittal_document_title()
returns trigger language plpgsql security invoker set search_path='' as $$
begin
  if tg_op='UPDATE' then
    new.document_title:=old.document_title;
    return new;
  end if;
  -- Capture only at issue creation, never from current MDR data during download
  -- or processing of a historical package. Existing item titles stay NULL.
  new.document_title:=null;
  if exists(select 1 from public.work_packages package
    where package.id=new.work_package_id
      and package.organisation_id=new.organisation_id
      and package.project_id=new.project_id
      and package.manifest->>'kind'='document_transmittal'
      and package.manifest->'pdf_layout_version'='2'::jsonb) then
    select document.title into new.document_title
      from public.documents document
      where document.id=new.document_id
        and document.organisation_id=new.organisation_id
        and document.project_id=new.project_id;
  end if;
  return new;
end $$;

revoke all on function public.stamp_project_report_pdf_layout(),
  public.stamp_transmittal_pdf_layout(),public.freeze_transmittal_document_title()
  from public,anon,authenticated,service_role;

-- zz_ runs after current report enrichment, retaining every calculated figure.
drop trigger if exists project_weekly_reports_zz_pdf_layout on public.project_weekly_reports;
create trigger project_weekly_reports_zz_pdf_layout
before insert or update of snapshot on public.project_weekly_reports
for each row execute function public.stamp_project_report_pdf_layout();

drop trigger if exists work_packages_pdf_layout on public.work_packages;
create trigger work_packages_pdf_layout
before insert or update of manifest on public.work_packages
for each row execute function public.stamp_transmittal_pdf_layout();

drop trigger if exists work_package_items_frozen_title on public.work_package_items;
create trigger work_package_items_frozen_title
before insert or update of document_title on public.work_package_items
for each row execute function public.freeze_transmittal_document_title();

comment on column public.work_package_items.document_title is
  'Frozen title for new v2 transmittals only. Historical items are not backfilled.';
notify pgrst,'reload schema';
commit;
